#!/usr/bin/env python3
"""Regenerate the SPIR-V headers of orbis-gfx-probe.

  gen_spv_header.py [--glslc PATH] [--check]

shaders_spv.h         compute shaders (committed; identical to Orbis 0.2.0's probe)
shaders_raster_spv.h  vertex/fragment shaders of the raster tests (generated at build time
                      by build/build-pack.sh; the probe builds without it and then reports
                      the raster tests as NOT_RUN "built without raster shaders")
"""
import argparse
import hashlib
import shutil
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHADERS = ["index_write", "saxpy_u32", "reduce"]
RASTER = ["raster.vert", "raster.frag"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--glslc", default=shutil.which("glslc"))
    ap.add_argument("--check", action="store_true", help="fail if header would change")
    a = ap.parse_args()
    if not a.glslc:
        print("glslc not found (install shaderc)", file=sys.stderr)
        return 1
    ver = subprocess.run([a.glslc, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    out = ["/* Generated by gen_spv_header.py -- do not edit. */",
           f"/* glslc: {ver} */", "#pragma once", "#include <stdint.h>", "#include <stddef.h>", ""]
    for name in SHADERS:
        src = HERE / "shaders" / f"{name}.comp"
        spv = HERE / "shaders" / f"{name}.spv"
        subprocess.run([a.glslc, "--target-env=vulkan1.1", "-O", "-o", str(spv), str(src)], check=True)
        blob = spv.read_bytes()
        words = struct.unpack(f"<{len(blob) // 4}I", blob)
        out.append(f"/* {name}.comp sha256 {hashlib.sha256(src.read_bytes()).hexdigest()} */")
        out.append(f"static const uint32_t spv_{name}[] = {{")
        for i in range(0, len(words), 8):
            out.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
        out.append("};")
        out.append(f"static const size_t spv_{name}_size = sizeof(spv_{name});")
        out.append("")
    text = "\n".join(out) + "\n"
    hdr = HERE / "shaders_spv.h"
    rout = ["/* Generated by gen_spv_header.py -- do not edit. */", f"/* glslc: {ver} */", "#pragma once",
            "#include <stdint.h>", "#include <stddef.h>", "#define ORBIS_HAVE_RASTER_SPV 1", ""]
    for fname in RASTER:
        src = HERE / "shaders" / fname
        spv = HERE / "shaders" / (fname + ".spv")
        subprocess.run([a.glslc, "--target-env=vulkan1.1", "-O", "-o", str(spv), str(src)], check=True)
        blob = spv.read_bytes()
        words = struct.unpack(f"<{len(blob) // 4}I", blob)
        ident = fname.replace(".", "_")
        rout.append(f"/* {fname} sha256 {hashlib.sha256(src.read_bytes()).hexdigest()} */")
        rout.append(f"static const uint32_t spv_{ident}[] = {{")
        for i in range(0, len(words), 8):
            rout.append("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",")
        rout.append("};")
        rout.append(f"static const size_t spv_{ident}_size = sizeof(spv_{ident});")
        rout.append("")
    (HERE / "shaders_raster_spv.h").write_text("\n".join(rout) + "\n")
    if a.check:
        if not hdr.exists() or hdr.read_text() != text:
            print("shaders_spv.h is stale", file=sys.stderr)
            return 1
        return 0
    hdr.write_text(text)
    print(f"wrote {hdr}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
